    private boolean gravar=false;
    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed
        // TODO add your handling code here:
       
        
        if(gravar==false)
        {   this.habilitar(true);
            this.btnInserir.setLabel("Gravar/Cancelar");
            
            this.limparCampos();
            this.txtID.setText( (banco.getUltimoid()+1) +"" );
            gravar=true;
            return;
        }
        if(gravar==true)
        {
            // 0 - 1- 2
            if(  JOptionPane.showConfirmDialog(null,"Deseja Gravar") !=0)
            {
                    gravar=false;
                    habilitar(false);
                    this.btnInserir.setLabel("Inserir");
                    return;
                
            }
        }
        
        String id,nome, senha;
        
        id = this.txtID.getText();
        nome = this.txtNome.getText();
        senha = this.txtSenha.getText();
        
        banco.inserir(id, nome, senha);
        
        iniciarDados();
        
        gravar=false;
        habilitar(false);
        this.btnInserir.setLabel("Inserir");
        
    }//GEN-LAST:event_btnInserirActionPerformed

