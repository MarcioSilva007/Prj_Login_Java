    private void pesquisar(String campo)
    {
        String pesquisa = 
         JOptionPane.showInputDialog("Digite o campo:"+campo);
        
        
          String valorlinha =  banco.pesquisa(pesquisa, campo);
          
          if(valorlinha.equals(""))
          {
              JOptionPane.showMessageDialog(null,"Dado não encontrado");
              return;
          }
        
        String id, nome, senha;
       
        //ID:1 -  Nom e  :  root      -    Senha:12345
        //0123456 789 10 11 12131415  1617 ...
        id = valorlinha.substring(
                valorlinha.indexOf(":")+1,
                valorlinha.indexOf("-"));
        
        nome = valorlinha.substring(
                valorlinha.indexOf("Nome:")+5,
                valorlinha.indexOf(" - Senha"));
        
        senha = valorlinha.substring(
                valorlinha.indexOf("Senha:")+6,
                valorlinha.length());
                
        
        this.txtID.setText(id+"");
        this.txtNome.setText(nome);
        this.txtSenha.setText(senha);
             
        
    }
